    private val mathPattern = Regex("""(\d+\s*[+\-*/×÷:=^]\s*\d+)|(\b[xyz]\s*[+\-=])|(\d+\s*[xyz]\b)""")

    fun detect(text: String): Subject {
        val lower = " " + text.lowercase() + " "
        val scores = mutableMapOf<Subject, Int>()
        for ((subject, words) in keywords) {
            var score = 0
            for (word in words) if (lower.contains(word)) score += if (word.length >= 6) 2 else 1
            if (score > 0) scores[subject] = score
        }
        if (mathPattern.containsMatchIn(lower)) scores[Subject.MATH] = (scores[Subject.MATH] ?: 0) + 2
        val best = scores.maxByOrNull { it.value } ?: return Subject.GENERAL
        return if (best.value >= 2) best.key else Subject.GENERAL
    }
