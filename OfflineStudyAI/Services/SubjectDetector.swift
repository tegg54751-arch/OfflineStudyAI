    static func detect(_ text: String) -> Subject {
        let lower = " " + text.lowercased() + " "
        var scores: [Subject: Int] = [:]
        for (subject, words) in keywords {
            var score = 0
            for word in words where lower.contains(word) {
                score += word.count >= 6 ? 2 : 1
            }
            if score > 0 { scores[subject] = score }
        }

        // Похоже на пример/уравнение: цифры и знаки операций.
        let mathPattern = #"(\d+\s*[\+\-\*/×÷:=^]\s*\d+)|(\b[xyz]\s*[\+\-=])|(\d+\s*[xyz]\b)"#
